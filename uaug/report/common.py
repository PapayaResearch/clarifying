def tiles_html(tiles: Iterable[Tuple[str, str]]) -> str:
    """Stat tiles row; values may contain markup, labels are pre-escaped text."""
    return '<div class="tiles">' + "".join(
        f'<div class="tile"><div class="v">{v}</div><div class="k">{k}</div></div>' for v, k in tiles
    ) + "</div>"


def render_page(path: str, *, eyebrow: str, tab_title: str, heading: str, sub: str, body: str, module: str, extra_css: str = ""):
    """Write a self-contained report page; heading/sub/body are pre-built HTML."""
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(tab_title)}</title><style>{BASE_CSS}{extra_css}</style></head><body>
<div class="wrap">
  <div class="eyebrow">{eyebrow}</div>
  <h1>{heading}</h1>
  <p class="sub">{sub}</p>
  {body}
  <div class="foot">Generated by <span class="mono">{module}</span></div>
</div></body></html>"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(page)
